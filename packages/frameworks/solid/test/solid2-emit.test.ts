import { readdirSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { resolve } from 'pathe';
import { describe, expect, test } from 'vitest';
import { parse } from 'yuku-parser';
import { buildEnrichedIr, type EnrichedIR } from '@frameless/compiler';
import { emit } from '../src/emitter/index.ts';
import { formatEmitted } from '../src/format-emitted.ts';
import { checkSources } from '../src/gate/index.ts';
import { emit as emitV2 } from '../src/v2.ts';

const root = resolve(import.meta.dirname, '..');
const goldenRoot = resolve(root, '../../compiler/test/goldens');

function byScenarioNumber(left: string, right: string): number {
	return Number(/(\d+)/.exec(left)![1]) - Number(/(\d+)/.exec(right)![1]);
}

function scenarioGoldens(): Array<readonly [string, string]> {
	const table = readdirSync(goldenRoot)
		.filter((entry) => /^s\d+-[\w-]+\.json$/.test(entry))
		.sort(byScenarioNumber)
		.map((entry) => [`S${/^s(\d+)-/.exec(entry)![1]}.tsx`, entry] as const);
	if (table.length === 0)
		throw new Error(`no s<n>-*.json scenario goldens found in ${goldenRoot}`);
	return table;
}

async function golden(name: string): Promise<EnrichedIR> {
	return JSON.parse(await readFile(resolve(goldenRoot, name), 'utf8')) as EnrichedIR;
}

function importSources(source: string): string[] {
	const program = parse(source, { sourceType: 'module', lang: 'tsx' }).program;
	return program.body.flatMap((statement) =>
		statement.type === 'ImportDeclaration' ? [statement.source.value] : [],
	);
}

function namedImportsFrom(source: string, specifier: string): string[] {
	const program = parse(source, { sourceType: 'module', lang: 'tsx' }).program;
	return program.body.flatMap((statement) => {
		if (statement.type !== 'ImportDeclaration' || statement.source.value !== specifier)
			return [];
		return statement.specifiers.flatMap((specifierNode) =>
			specifierNode.type === 'ImportSpecifier' && specifierNode.imported.type === 'Identifier'
				? [specifierNode.imported.name]
				: [],
		);
	});
}

describe('Solid 2 RC emission', () => {
	test('default emit stays on Solid 1 and matches the bound v2 entry for generation 2', async () => {
		const ir = await golden('s2-keyed-todo.json');
		const v1 = emit(ir);
		const v2 = emit(ir, { generation: '2' });
		expect(v1).toBe(emit(ir, { generation: '1' }));
		expect(v2).toBe(emitV2(ir));
		expect(v1).not.toBe(v2);
	});

	test('S2 v2 moves store APIs onto solid-js and drops produce, attr:value, and the store subpath', async () => {
		const ir = await golden('s2-keyed-todo.json');
		const source = await formatEmitted(emit(ir, { generation: '2' }));
		expect(source.startsWith('// @generated by @frameless/solid (solid-2); do not edit.\n')).toBe(
			true,
		);
		expect(importSources(source)).toEqual(['solid-js']);
		expect(importSources(source)).not.toContain('solid-js/store');
		expect(namedImportsFrom(source, 'solid-js')).toEqual(
			expect.arrayContaining(['createSignal', 'createStore', 'reconcile', 'For', 'Show']),
		);
		expect(namedImportsFrom(source, 'solid-js')).not.toContain('produce');
		expect(source).not.toContain('attr:value');
		expect(source).not.toMatch(/setTodos\(\s*produce\(/);
		expect(source).toMatch(/setTodos\(\s*\(storeDraft\)\s*=>/);
		expect(source).toMatch(/setTodos\(\s*reconcile\(/);
	});

	test('S1 v2 is a no-store module and still does not invent Solid 1-only forms', async () => {
		const ir = await golden('s1-render-once.json');
		const source = await formatEmitted(emit(ir, { generation: '2' }));
		expect(importSources(source)).toEqual(['solid-js']);
		expect(namedImportsFrom(source, 'solid-js')).toEqual(
			expect.arrayContaining(['createSignal', 'untrack', 'Show']),
		);
		expect(source).not.toContain('solid-js/store');
		expect(source).not.toContain('attr:value');
		expect(source).not.toContain('produce');
	});

	test('S3 v2 drops the attr:value pair that Solid 2 removed', async () => {
		const ir = await golden('s3-event-form.json');
		const source = await formatEmitted(emit(ir, { generation: '2' }));
		expect(source).toMatch(/value=\{text\(\)\}\s+onInput=/);
		expect(source).not.toContain('attr:value');
	});

	test('the v2 gate accepts S2 output that the v1 gate would reject for missing attr:value', async () => {
		const ir = await golden('s2-keyed-todo.json');
		const source = await formatEmitted(emit(ir, { generation: '2' }));
		const v2 = await checkSources([{ file: 'generated-v2/S2.tsx', source, artifact: ir }], {
			generation: '2',
		});
		expect(v2.violations).toEqual([]);
		const v1 = await checkSources([{ file: 'generated/S2.tsx', source, artifact: ir }], {
			generation: '1',
		});
		expect(v1.violations.map((entry) => entry.policy)).toEqual(
			expect.arrayContaining([
				'controlled-input',
				'store-write-shape',
				'solid-import-allowlist',
			]),
		);
	});

	test('composition attach lowers onMount to onSettled and keeps store APIs on solid-js', async () => {
		const filename = 'test/composition-fixtures/C4-attach.tsrx';
		const source = await readFile(resolve(root, filename), 'utf8');
		const ir = await buildEnrichedIr({ filename, source });
		const emitted = await formatEmitted(emit(ir, { generation: '2' }));
		expect(emitted).toContain('onSettled');
		expect(emitted).not.toContain('onMount');
		expect(importSources(emitted)).not.toContain('solid-js/store');
		const gate = await checkSources(
			[{ file: 'generated-v2/C4-attach.tsx', source: emitted, artifact: ir }],
			{ generation: '2' },
		);
		// eslint-plugin-solid 0.14.5 treats onMount as a tracked scope and does
		// not yet know onSettled, so reactivity is a known plugin lag on this
		// fixture rather than an emitter defect.
		expect(gate.violations.map((entry) => entry.policy)).toEqual(['eslint:solid/reactivity']);
	});

	for (const [output, goldenName] of scenarioGoldens()) {
		test(`${output} generation 2 is stable, store-subpath-free, and attr-namespace-free`, async () => {
			const ir = await golden(goldenName);
			const source = await formatEmitted(emit(ir, { generation: '2' }));
			expect(source).toContain('@frameless/solid (solid-2)');
			expect(importSources(source)).not.toContain('solid-js/store');
			expect(source).not.toContain('attr:value');
			expect(source).not.toMatch(/\bproduce\s*\(/);
		});
	}
});
